-- Baseline schema for Store Tracker.
--
-- Flyway owns the schema from this point on; Hibernate runs with
-- ddl-auto=validate in every profile, so this file must stay in sync with the
-- entity mappings. The SQL is intentionally portable between H2 (dev, tests)
-- and PostgreSQL (postgres, prod).

create table visits (
    id          bigint generated by default as identity primary key,
    person_name varchar(255) not null,
    entry_time  timestamp(6) not null,
    exit_time   timestamp(6),
    total_spent numeric(12,2),
    version     bigint not null default 0,
    created_at  timestamp(6) not null,
    updated_at  timestamp(6) not null
);

create table purchased_items (
    id         bigint generated by default as identity primary key,
    name       varchar(255) not null,
    price      numeric(12,2) not null,
    quantity   integer not null,
    visit_id   bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_purchased_items_visit foreign key (visit_id) references visits (id)
);

create index idx_visits_entry_time on visits (entry_time);
create index idx_visits_exit_time on visits (exit_time);
create index idx_purchased_items_visit on purchased_items (visit_id);
